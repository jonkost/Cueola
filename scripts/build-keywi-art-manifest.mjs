#!/usr/bin/env node
/* Rebuilds the KeyWi Bird art-pack manifest from what is on disk.
 *
 * Every folder under assets/keywi-art/ becomes a pack in the key editor's art
 * bucket; every svg/png/webp/jpg/gif inside it becomes a one-click key image.
 * This is how the owner adds their own meme/GIF bank without touching code:
 *   1. Drop the files into assets/keywi-art/<pack-name>/  (e.g. memes/)
 *   2. node scripts/build-keywi-art-manifest.mjs
 *   3. node scripts/bump-cache.mjs   (so browsers pick up the new manifest)
 * Only ship files you have the rights to; this repo deliberately contains no
 * third-party meme images.
 *
 * Output: assets/keywi-art/manifest.js (a classic global script, loaded by
 * index.html before cueola-streamdeck.js). GIFs animate on keys.
 */
import { readdirSync, statSync, writeFileSync, existsSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const artDir = join(root, 'assets', 'keywi-art');
const FILE_RE = /\.(svg|png|webp|jpe?g|gif)$/i;

function titleCase(name) {
  return name.replace(/\.[^.]+$/, '').split(/[-_]+/)
    .map(w => w ? w[0].toUpperCase() + w.slice(1) : '')
    .join(' ').trim() || name;
}

const packs = [];
if (existsSync(artDir)) {
  for (const entry of readdirSync(artDir).sort()) {
    const packPath = join(artDir, entry);
    if (!statSync(packPath).isDirectory()) continue;
    const items = readdirSync(packPath).sort()
      .filter(f => FILE_RE.test(f))
      .map(f => ({ label: titleCase(f), src: `assets/keywi-art/${entry}/${f}` }));
    if (items.length) packs.push({ name: titleCase(entry), items });
  }
}

const out = '// GENERATED by scripts/build-keywi-art-manifest.mjs. Do not edit by hand;\n'
  + '// add or remove files under assets/keywi-art/<pack>/ and rerun the script.\n'
  + 'window.KEYWI_ART_MANIFEST = ' + JSON.stringify({ packs }, null, 2) + ';\n';
writeFileSync(join(artDir, 'manifest.js'), out);
const total = packs.reduce((n, p) => n + p.items.length, 0);
console.log(`Manifest: ${packs.length} pack(s), ${total} item(s) -> assets/keywi-art/manifest.js`);
for (const p of packs) console.log(`  ${p.name}: ${p.items.length}`);
